#!/usr/bin/env python3
r"""Stage a kernel beside the UniXNU menu, for the chainload route.

    python3 scripts/stage-kernel.py --kernel build/kernel/kernel.macho --unique-chip-id HEX \
        [--trustcache FILE] [--data FILE] [--out build/boot]

The menu stage is what the phone has run: UniXNU finds its configuration on EFIESP, draws on
the panel and takes the volume keys (scripts/build-payload.sh). This adds the second stage to
the same tree: DarwinBoot as a driver, an `xnu` entry that hands it the kernel and the ADT
sidecar, and the files the loader reads beside the kernel (`<kernel>.adt`, `<kernel>.trustcache`).

Nothing here reaches the phone unchecked. The kernel must be a 64-bit ARM Mach-O executable
(DarwinBoot parses it as one and refuses anything else), the ADT is generated by the board's
own tool and accepted by its checker, and scripts/check-payload.py re-reads the staged
configuration and requires every file it names to be in the tree. The result is a plain FAT
directory, so nothing is flashed: it is copied over \EFI on EFIESP or onto the microSD card.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - the CI runner has 3.11
    sys.exit("python3.11 or newer is required (tomllib)")

ROOT = Path(__file__).resolve().parents[1]
BASE_TREE = ROOT / "payload"
CONFIG_REL = "EFI/UniXNU/unixnu.toml"
PAYLOADS_REL = "EFI/UniXNU/Payloads"
KERNEL_NAME = "kernel.macho"

# The line in payload/EFI/UniXNU/unixnu.toml that the kernel entry replaces. Keeping the menu
# configuration the source of truth means the UI keys, the systemd-style action entries and
# the comments about the panel layout are not copied into a second config that then drifts.
MARKER = "# stage-kernel.py: kernel entry"

# DarwinBoot's own limits: it copies the command line into a 1024-byte buffer, and the ADT
# tool and payload step already refuse anything longer than 1000 bytes.
ARGUMENT = re.compile(r"[A-Za-z0-9_.\-]+(=[A-Za-z0-9_.,\-]+)?")

MH_MAGIC_64 = 0xFEEDFACF
MH_EXECUTE = 0x2
CPU_TYPE_ARM64 = 0x0100000C


def fail(message: str):
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def board_section() -> dict:
    board_path = ROOT / "board.toml"
    if not board_path.is_file():
        fail(f"{board_path} is missing; run this from the device repository")
    board = tomllib.loads(board_path.read_text())
    spec = board.get("payload")
    if not spec:
        fail("board.toml has no [payload]; it names the kernel arguments, the DRAM size and "
             "the ADT generator this stage runs (see the section's comment in board.toml)")
    adt = spec.get("adt") or {}
    if not adt.get("tool"):
        fail("board.toml [payload.adt] has no tool; it is the ADT generator for this SoC")
    if spec.get("dram_size") is None:
        fail("board.toml [payload] has no dram_size; the ADT's /memory node needs the figure "
             "the firmware reports, not the marketing one")
    return spec


def check_kernel(path: Path) -> dict:
    """The header DarwinBoot parses. Refusing here is cheaper than an EFI_LOAD_ERROR on a panel."""
    size = path.stat().st_size
    if size < 32:
        fail(f"{path} is {size} bytes; that is not a Mach-O")
    head = path.read_bytes()[:32]
    magic, cputype, cpusubtype, filetype, ncmds, sizeofcmds = (
        int.from_bytes(head[0:4], "little"), int.from_bytes(head[4:8], "little"),
        int.from_bytes(head[8:12], "little"), int.from_bytes(head[12:16], "little"),
        int.from_bytes(head[16:20], "little"), int.from_bytes(head[20:24], "little"))
    if magic != MH_MAGIC_64:
        fail(f"{path} does not start with MH_MAGIC_64 (0x{magic:08x}); DarwinBoot parses a "
             "64-bit Mach-O and this is not one")
    if cputype != CPU_TYPE_ARM64:
        fail(f"{path} is cputype 0x{cputype:08x}; this kernel has to be CPU_TYPE_ARM64")
    if filetype != MH_EXECUTE:
        fail(f"{path} is filetype 0x{filetype:08x}; DarwinBoot requires MH_EXECUTE (0x2)")
    if ncmds == 0 or sizeofcmds == 0 or 32 + sizeofcmds > size:
        fail(f"{path} has {ncmds} load commands taking {sizeofcmds} bytes in a {size}-byte "
             "file; the header does not describe its own contents")
    return {"size": size, "ncmds": ncmds}


def kernel_arguments(spec: dict, override: str | None) -> str:
    arguments = spec.get("kernel_args", [])
    if not isinstance(arguments, list) or not all(isinstance(item, str) for item in arguments):
        fail("board.toml [payload] kernel_args is not an array of strings")
    if override is not None:
        arguments = override.split()
    for argument in arguments:
        if not ARGUMENT.fullmatch(argument):
            fail(f"unsupported kernel argument: {argument!r}")
    line = " ".join(arguments)
    if len(line) > 1000:
        fail(f"the kernel command line is {len(line)} bytes; DarwinBoot's buffer is 1024")
    return line


def adt_command(spec: dict, adt: Path, args: argparse.Namespace) -> list[str]:
    values = spec["adt"]
    command = [sys.executable, str(ROOT / values["tool"]), "--output", str(adt),
               "--dram-size", hex(spec["dram_size"])]
    for key, flag in (("owned_memory_size", "--owned-memory-size"),
                      ("root_match_volume_uuid", "--root-match-volume-uuid"),
                      ("chip_id", "--chip-id"), ("cpu_regs", "--cpu-regs"),
                      ("psci_method", "--psci-method")):
        if values.get(key) is not None:
            command += [flag, str(values[key])]
    if args.dram_base is not None:
        command += ["--dram-base", hex(args.dram_base)]
    if args.chip_id is not None:
        command += ["--chip-id", str(args.chip_id)]
    command += ["--unique-chip-id", args.unique_chip_id]
    if args.trustcache:
        command.append("--trust-cache")
    if args.data:
        command.append("--packed-data-ramdisk" if values.get("packed_data_ramdisk")
                       else "--data-ramdisk")
        if values.get("persistent_data"):
            command.append("--persistent-data")
    for fixup in spec.get("text_fixups", []):
        command += ["--text-fixup", fixup]
    return command


def render_config(spec: dict, menu_tree: Path, initrd: bool, arguments: str) -> str:
    source = (menu_tree / CONFIG_REL).read_text()
    if source.count(MARKER) != 1:
        fail(f"{CONFIG_REL} needs exactly one {MARKER!r} line; the kernel entry is inserted "
             "there and everywhere else would be a guess")
    title = spec.get("title", "UniXNU")
    if '"' in title or "\\" in title:
        fail(f'board.toml [payload] title {title!r} cannot go in a TOML string unchanged')
    entry = (f'[[driver]]\npath = "Drivers/DarwinBoot.efi"\nconnect = true\n\n'
             f'[[entry]]\nid = "xnu"\ntitle = "{title}"\ntype = "xnu"\n'
             f'path = "Payloads/{KERNEL_NAME}"\n')
    if initrd:
        entry += 'initrd = "Payloads/scratch-data.img"\n'
    entry += f'args = "{arguments}"\n'
    staged = source.replace(MARKER, entry)
    # The kernel is the entry this stage exists for, so it becomes the countdown default. The
    # menu-only config keeps "exit" because none of its entries can boot a kernel.
    if staged.count('default = "exit"') != 1:
        fail(f'{CONFIG_REL} needs exactly one default = "exit" to replace')
    return staged.replace('default = "exit"', 'default = "xnu"')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--kernel", type=Path, required=True,
                        help="the kernel Mach-O, e.g. the kernel job's prelinked image")
    parser.add_argument("--trustcache", type=Path,
                        help="the trust cache bundle DarwinBoot validates, if the image needs one")
    parser.add_argument("--data", type=Path,
                        help="the Data ramdisk seed; it becomes Payloads/scratch-data.img")
    parser.add_argument("--menu-tree", type=Path,
                        help="the menu stage to add to: out/payload from build-payload.sh "
                             "(default: out/payload if it exists, else payload/)")
    parser.add_argument("--out", type=Path, default=ROOT / "build/boot",
                        help="the staged tree (default: build/boot)")
    parser.add_argument("--unique-chip-id", required=True,
                        help="64-bit platform seed in hex; it is not stored in this repository")
    parser.add_argument("--dram-size", type=lambda value: int(value, 0),
                        help="override board.toml [payload] dram_size")
    parser.add_argument("--dram-base", type=lambda value: int(value, 0),
                        help="override the ADT DRAM base (default: the SoC's 0x80000000)")
    parser.add_argument("--chip-id", type=lambda value: int(value, 0),
                        help="override board.toml [payload.adt] chip_id")
    parser.add_argument("--args", help="override board.toml [payload] kernel_args")
    args = parser.parse_args()

    if not re.fullmatch(r"[0-9a-fA-F]{1,16}", args.unique_chip_id):
        fail(f"--unique-chip-id {args.unique_chip_id!r} is not 1-16 hex digits")
    spec = board_section()
    if args.dram_size is not None:
        spec = dict(spec, dram_size=args.dram_size)
    if not args.kernel.is_file():
        fail(f"kernel not found: {args.kernel}; pass the kernel job's artifact")
    header = check_kernel(args.kernel)
    arguments = kernel_arguments(spec, args.args)
    for name, path in (("trust cache", args.trustcache), ("Data seed", args.data)):
        if path is not None and not path.is_file():
            fail(f"{name} not found: {path}")

    # The menu stage carries the two EFI binaries; the repository's payload/ directory only
    # carries the configuration, so adding a kernel to it directly would stage a tree the
    # firmware cannot start. Refusing here says which command produces the missing half.
    menu_tree = args.menu_tree or (ROOT / "out/payload" if (ROOT / "out/payload").is_dir()
                                   else BASE_TREE)
    if not menu_tree.is_absolute():
        menu_tree = ROOT / menu_tree
    if not (menu_tree / CONFIG_REL).is_file():
        fail(f"{menu_tree} has no {CONFIG_REL}; run scripts/build-payload.sh first")
    if not (menu_tree / "EFI/UniXNU/Drivers/DarwinBoot.efi").is_file():
        fail(f"{menu_tree} has no EFI/UniXNU/Drivers/DarwinBoot.efi; the menu stage is built "
             "by scripts/build-payload.sh, which puts the loader beside the menu")

    out = args.out if args.out.is_absolute() else ROOT / args.out
    if out.resolve() == menu_tree.resolve():
        fail("--out is the menu tree; stage into a new directory so the menu build stays intact")
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(menu_tree, out)
    payloads = out / PAYLOADS_REL
    payloads.mkdir(parents=True, exist_ok=True)

    shutil.copyfile(args.kernel, payloads / KERNEL_NAME)
    adt = payloads / f"{KERNEL_NAME}.adt"
    command = adt_command(spec, adt, args)
    print("== adt: " + " ".join(command[1:]))
    result = subprocess.run(command, cwd=ROOT)
    if result.returncode != 0:
        fail("the ADT generator refused its arguments")
    checked = subprocess.run([sys.executable, str(ROOT / "scripts/check-adt.py"), str(adt)],
                             cwd=ROOT)
    if checked.returncode != 0:
        fail("scripts/check-adt.py rejected the generated ADT")
    if args.trustcache:
        shutil.copyfile(args.trustcache, payloads / f"{KERNEL_NAME}.trustcache")
    if args.data:
        shutil.copyfile(args.data, payloads / "scratch-data.img")
    (out / CONFIG_REL).write_text(render_config(spec, menu_tree, bool(args.data), arguments))

    print("== check")
    checked = subprocess.run([sys.executable, str(ROOT / "scripts/check-payload.py"),
                              "--config", str(out / CONFIG_REL), "--payload-dir", str(out)],
                             cwd=ROOT)
    if checked.returncode != 0:
        fail("the staged tree does not pass scripts/check-payload.py")

    staged = sorted(path for path in out.rglob("*") if path.is_file())
    total = sum(path.stat().st_size for path in staged)
    print("== output")
    print(f"{out}")
    for path in staged:
        print(f"  {path.relative_to(out).as_posix():<44} {path.stat().st_size:>10} B  {sha256(path)[:16]}")
    print(f"  {'total':<44} {total:>10} B")
    print()
    print(f"kernel {header['size']} B, {header['ncmds']} load commands, args {arguments!r}")
    print(f"copy {out / 'EFI'} over \\EFI on EFIESP, or onto the microSD card when the tree is "
          "bigger than the partition")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
